#!/usr/bin/env node
/**
 * build-i18n.mjs — bundle every `locales/<code>/messages.json` into
 * `src/i18n.generated.ts`, which esbuild inlines into main.js.
 *
 * One generated module (not a runtime fetch) because Obsidian plugins run from a
 * single main.js with no asset pipeline.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LOCALES = path.join(ROOT, "locales");
const OUT = path.join(ROOT, "src", "i18n.generated.ts");

const locales = {};
for (const entry of fs.readdirSync(LOCALES, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const file = path.join(LOCALES, entry.name, "messages.json");
  if (!fs.existsSync(file)) continue;
  locales[entry.name] = JSON.parse(fs.readFileSync(file, "utf8"));
}

const body = [
  "/* Generated by scripts/build-i18n.mjs — do not edit. */",
  "export type LocaleCatalogue = Record<string, { message: string }>;",
  `export const LOCALES: Record<string, LocaleCatalogue> = ${JSON.stringify(locales, null, 2)};`,
  `export const LOCALE_CODES: string[] = ${JSON.stringify(Object.keys(locales))};`,
  "",
].join("\n");

fs.writeFileSync(OUT, body);
console.log(`[build-i18n] ${Object.keys(locales).length} locales → src/i18n.generated.ts (${(body.length / 1024).toFixed(1)} KB)`);
